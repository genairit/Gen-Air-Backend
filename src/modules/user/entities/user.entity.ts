import {
  Table,
  Model,
  Column,
  Default,
  DataType,
  CreatedAt,
  DeletedAt,
  UpdatedAt,
  PrimaryKey,
  DefaultScope,
} from 'sequelize-typescript';

import {
  USER_ROLE_VALUES,
  type UserRoleType,
} from '@Constants/user-role.constant';

import { FIELD_LENGTHS } from '@Constants/field-length.constant';
import { IUser, TUserCreationAttributes } from '../interfaces/user.interface';

@DefaultScope(() => ({ attributes: { exclude: ['passwordHash'] } }))
@Table({
  tableName: 'users',
  paranoid: true,
  indexes: [
    { name: 'idx_users_role', fields: ['role'], where: { deleted_at: null } },
  ],
})
export class User
  extends Model<IUser, TUserCreationAttributes>
  implements IUser
{
  @PrimaryKey
  @Default(DataType.UUIDV4)
  @Column(DataType.UUID)
  declare id: string;

  // Generated by the database sequence, so Sequelize must not require it on insert.
  @Column(DataType.STRING(FIELD_LENGTHS.EMPLOYEE_NUMBER))
  declare employeeNumber: string;

  @Column({ allowNull: false, type: DataType.STRING(FIELD_LENGTHS.USER_NAME) })
  declare firstName: string;

  @Column({ allowNull: false, type: DataType.STRING(FIELD_LENGTHS.USER_NAME) })
  declare lastName: string;

  @Column({ allowNull: false, unique: true, type: DataType.CITEXT })
  declare email: string;

  @Column({ allowNull: false, type: DataType.STRING(FIELD_LENGTHS.PHONE) })
  declare phone: string;

  @Column({ allowNull: false, type: DataType.ENUM(...USER_ROLE_VALUES) })
  declare role: UserRoleType;

  @Column({
    allowNull: false,
    type: DataType.STRING(FIELD_LENGTHS.PASSWORD_HASH),
  })
  declare passwordHash: string;

  @CreatedAt
  declare createdAt: Date;

  @UpdatedAt
  declare updatedAt: Date;

  @DeletedAt
  declare deletedAt: Date | null;
}
