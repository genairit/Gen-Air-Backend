BEGIN;
CREATE TABLE permissions (
  key text PRIMARY KEY,
  feature text NOT NULL,
  action text NOT NULL,
  CONSTRAINT chk_permissions_key CHECK (key = feature || '.' || action),
  CONSTRAINT uq_permissions_feature_action UNIQUE (feature, action)
);
CREATE TABLE role_permissions (
  role user_role NOT NULL,
  permission_key text NOT NULL REFERENCES permissions(key) ON DELETE RESTRICT,
  PRIMARY KEY (role, permission_key)
);
CREATE INDEX idx_role_permissions_permission_key ON role_permissions(permission_key);
ALTER TABLE permissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE role_permissions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON permissions, role_permissions FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON permissions, role_permissions FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON permissions, role_permissions FROM authenticated;
  END IF;
END $$;
